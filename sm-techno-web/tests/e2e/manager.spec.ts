import { expect, test } from '@playwright/test';

// Run only through test:auth:e2e: its launcher scrubs all production settings.
test('manager cabinet saves manual sales, previews excess commission and protects history', async ({ page, request }, testInfo) => {
  test.setTimeout(120_000);
  const adminResponse = await request.post('/api/auth/login', { data: { username: 'admin', password: 'admin-e2e-password' } });
  expect(adminResponse.ok()).toBeTruthy();
  const admin = await adminResponse.json();
  const headers = { Authorization: `Bearer ${admin.token}` };
  const username = `manager-${testInfo.project.name}-${Date.now()}`;
  const created = await request.post('/api/users', { headers, data: { username, password: 'manager-test-password', role: 'user', fullName: 'Тестовый менеджер' } });
  expect(created.ok()).toBeTruthy();
  const login = await request.post('/api/auth/login', { data: { username, password: 'manager-test-password' } });
  const managerSession = await login.json();
  const managerHeaders = { Authorization: `Bearer ${managerSession.token}` };
  const own = await request.get('/api/manager/dashboard?month=2026-10', { headers: managerHeaders });
  const account = (await own.json()).account.id;
  await page.addInitScript(session => window.localStorage.setItem('sm-techno-auth-session', JSON.stringify(session)), admin);
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/manager');
  await page.getByLabel('Месяц', { exact: true }).fill('2026-10');
  await page.getByLabel('Кабинет сотрудника').selectOption(String(account));
  await expect(page.getByRole('heading', { name: 'Тестовый менеджер', exact: true })).toBeVisible();
  await expect(page.getByText('Задайте план и условия начисления.', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Настроить условия' }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('План продаж, ₽').fill('1000000');
  await dialog.getByLabel('Фиксированная часть, ₽').fill('50000');
  await dialog.getByLabel('Ставка для новых продаж, %').fill('5');
  await dialog.getByRole('button', { name: 'Рассчитать изменения' }).click();
  await expect(dialog.getByRole('heading', { name: 'После изменения' })).toBeVisible();
  await dialog.getByRole('button', { name: 'Сохранить изменения' }).click();
  await expect(dialog).toHaveCount(0);
  await page.getByRole('button', { name: 'Добавить продажу' }).click();
  await dialog.getByLabel('Наименование клиента для документов').fill('ООО «Промснаб»');
  await dialog.getByLabel('Сумма продажи, ₽').fill('1200000');
  await dialog.getByRole('button', { name: 'Рассчитать изменения' }).click();
  await expect(dialog.getByText(/10\s000/).first()).toBeVisible();
  await dialog.getByRole('button', { name: 'Сохранить изменения' }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Комиссия сверх плана' }) })).toContainText(/10\s000/);
  await page.reload();
  await page.getByLabel('Кабинет сотрудника').selectOption(String(account));
  await expect(page.getByText('ООО «Промснаб»', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  const logo = page.getByRole('img', { name: /СМ ТЕХНО|SM Techno/i }).filter({ visible: true });
  await expect(logo.first()).toHaveAttribute('src', /logo\.png/);
  await page.screenshot({ path: testInfo.outputPath('manager.png'), fullPage: true });
  await page.getByRole('button', { name: 'Закрыть месяц', exact: true }).click();
  await dialog.getByLabel('Причина изменения').fill('Проверено администратором');
  await dialog.getByRole('button', { name: 'Рассчитать изменения' }).click();
  await dialog.getByRole('button', { name: 'Сохранить изменения' }).click();
  await expect(page.getByRole('button', { name: 'Открыть месяц', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Добавить продажу' })).toHaveCount(0);
  await page.getByRole('button', { name: 'История изменений' }).click();
  await expect(dialog.getByText('Проверено администратором', { exact: false }).first()).toBeVisible();
  await dialog.getByRole('button', { name: 'Закрыть', exact: true }).click();
  const boss = await request.get('/api/manager/dashboard?month=2026-10', { headers });
  const forbidden = await request.get(`/api/manager/dashboard?month=2026-10&managerId=${(await boss.json()).account.id}`, { headers: managerHeaders });
  expect(forbidden.status()).toBe(403);
  expect(errors).toEqual([]);
});
